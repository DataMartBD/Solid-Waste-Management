// Small pieces shared by the City Oversight tabs.

import { IconAlert, IconDownload } from '../components/Icons.jsx'
import { useLang } from '../i18n/index.jsx'

export function Loading() {
  return <div className="center muted" style={{ padding: 32 }}><span className="spinner spinner-dark" /></div>
}

export function Failed({ error, onRetry }) {
  const { t } = useLang()
  return (
    <div className="form-note bad" style={{ margin: 16 }}>
      <IconAlert size={15} /><span className="grow">{error?.detail || t('common.requestFailed')}</span>
      <button className="btn btn-ghost btn-sm" onClick={onRetry}>{t('common.retry')}</button>
    </div>
  )
}

// CSV / Excel / PDF, generated by the report's own endpoint (?format=…).
export function ExportButtons({ exporter, filename }) {
  const { t } = useLang()
  return (
    <div className="row gap-8">
      {['csv', 'xlsx', 'pdf'].map((format) => (
        <button key={format} className="btn btn-ghost btn-sm"
          onClick={() => exporter({ format, filename: `${filename}.${format}` })}>
          <IconDownload size={14} /> {t(`oversight.export.${format}`)}
        </button>
      ))}
    </div>
  )
}
